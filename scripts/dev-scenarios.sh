#!/usr/bin/env bash
set -euo pipefail

# ──────────────────────────────────────────────────────────────────────────
# 전체 유저 스토리 시나리오 러너.
# DB를 초기화한 뒤 모든 시나리오를 실제 화면 흐름 순서대로 실행한다.
# GUI 없이 API만으로 유저 스토리 전체가 동작하는지 한 번에 검증하는 용도다.
#
# 각 시나리오는 단언(assert)에 실패하면 즉시 비정상 종료(exit 1)하므로,
# 이 러너가 끝까지 통과하면 핵심 유저 스토리가 구현상 모두 동작한다는 뜻이다.
#
# 시나리오 목록은 docs/specs/user-stories.md 참조.
# 전제: 서버가 떠 있어야 한다 (make dev / make dev-local).
# ──────────────────────────────────────────────────────────────────────────

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

echo "############################################################"
echo "# 유저 스토리 시나리오 전체 검증"
echo "############################################################"

echo ""
echo ">>> DB 초기화 + dev 유저 시드 (dev:reset)"
bash scripts/dev-reset-all.sh >/dev/null
echo "    완료"

echo ""
echo "============================================================"
bash scripts/dev-scenario-onboarding.sh

echo ""
echo "============================================================"
bash scripts/dev-scenario-collab.sh

echo ""
echo "############################################################"
echo "# 모든 시나리오 통과 — 유저 스토리 end-to-end 검증 완료"
echo "############################################################"
